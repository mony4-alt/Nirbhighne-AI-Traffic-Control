"""
robustness_eval/generate_yamls.py
===================================
Utility script to generate properly-formatted YOLO data YAML files
for all three dataset variants (rgb, grayscale, lowres).

This is called automatically by 06_run_all.py, but can also be
run manually if you want to just generate/update the YAML files.

Usage:
  python generate_yamls.py --dataset_root PATH --eval_root PATH

Arguments:
  --dataset_root : Path to the ORIGINAL YOLO dataset root
  --eval_root    : Path to the robustness_eval/ folder
"""

import argparse
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if SCRIPT_DIR not in sys.path:
    sys.path.insert(0, SCRIPT_DIR)

from config import (
    CLASS_NAMES,
    VARIANT_RGB,
    VARIANT_GRAYSCALE,
    VARIANT_LOWRES,
    LOWRES_SCALE,
    ensure_dirs,
    get_dataset_dir,
    get_yaml_path,
    get_results_dir,
)


def write_yaml(yaml_path: str, dataset_dir: str, variant: str) -> None:
    """Writes a YOLO data YAML for the given variant."""
    ensure_dirs(os.path.dirname(yaml_path))
    base = dataset_dir.replace("\\", "/")

    comment_map = {
        VARIANT_RGB:       "Original RGB dataset",
        VARIANT_GRAYSCALE: "Grayscale variant",
        VARIANT_LOWRES:    f"Low-resolution variant (scale={LOWRES_SCALE})",
    }

    content = (
        f"# Auto-generated by generate_yamls.py\n"
        f"# {comment_map.get(variant, variant)}\n\n"
        f"path: {base}\n"
        f"train: images/train\n"
        f"val:   images/val\n"
        f"test:  images/test\n\n"
        f"nc: {len(CLASS_NAMES)}\n"
        f"names: {CLASS_NAMES}\n"
    )

    with open(yaml_path, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"  [OK] {variant:<12} → {yaml_path}")


def generate_all_yamls(dataset_root: str, eval_root: str) -> dict:
    """
    Generates YAML files for all three variants.
    Returns a dict mapping variant → yaml_path.
    """
    yamls = {}
    print(f"\n{'='*60}")
    print(f"  Generating YOLO Data YAML files")
    print(f"{'='*60}")

    for variant in (VARIANT_RGB, VARIANT_GRAYSCALE, VARIANT_LOWRES):
        dataset_dir = get_dataset_dir(dataset_root, variant)
        yaml_path   = get_yaml_path(eval_root, variant)
        write_yaml(yaml_path, dataset_dir, variant)
        yamls[variant] = yaml_path

    print()
    return yamls


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate YOLO data YAML files for all dataset variants."
    )
    parser.add_argument("--dataset_root", required=True)
    parser.add_argument("--eval_root",    required=True)
    args = parser.parse_args()

    if not os.path.isdir(args.dataset_root):
        print(f"[ERROR] dataset_root does not exist: {args.dataset_root}")
        sys.exit(1)
    if not os.path.isdir(args.eval_root):
        print(f"[ERROR] eval_root does not exist: {args.eval_root}")
        sys.exit(1)

    generate_all_yamls(
        os.path.abspath(args.dataset_root),
        os.path.abspath(args.eval_root),
    )
    print("[DONE] All YAML files generated.\n")


if __name__ == "__main__":
    main()
