"""
robustness_eval/02_prepare_lowres.py
=====================================
Creates a reduced-resolution YOLO dataset (75% of original dimensions).

What it does:
  - Reads every image from images/train, images/val, images/test
  - Resizes each image to 75% of its width and height using cv2.INTER_AREA
    (best quality for downscaling)
  - YOLO labels are in normalized coordinates, so they remain correct
    after resizing — they are copied unchanged
  - Creates a properly formatted data_lowres.yaml
  - Never modifies the original dataset

Resolution example:
  Original  : 1920×1080
  Reduced   : 1440×810  (75% of each dimension = ~56% of pixel count)

Usage:
  python 02_prepare_lowres.py --dataset_root PATH --eval_root PATH

  --dataset_root : Path to the original YOLO dataset root
  --eval_root    : Path to the robustness_eval/ folder

Example:
  python robustness_eval/02_prepare_lowres.py \
      --dataset_root "C:/Users/monst/datasets/final_11class_split" \
      --eval_root    "C:/Users/monst/OneDrive/Documents/Naiem/portable alifs cap/VehicleDetector/robustness_eval"
"""

import argparse
import os
import shutil
import sys
import cv2

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if SCRIPT_DIR not in sys.path:
    sys.path.insert(0, SCRIPT_DIR)

from config import (
    CLASS_NAMES,
    IMAGE_EXTENSIONS,
    LOWRES_SCALE,
    VARIANT_LOWRES,
    ensure_dirs,
    get_dataset_dir,
    get_yaml_path,
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _iter_splits(dataset_root: str):
    """Yields (split_name, images_dir, labels_dir) for train / val / test."""
    for split in ("train", "val", "test"):
        images_dir = os.path.join(dataset_root, "images", split)
        labels_dir = os.path.join(dataset_root, "labels", split)
        if os.path.isdir(images_dir):
            yield split, images_dir, labels_dir
        else:
            print(f"  [SKIP] Split '{split}' not found at: {images_dir}")


def _is_image(filename: str) -> bool:
    return os.path.splitext(filename)[1].lower() in IMAGE_EXTENSIONS


def resize_dataset(
    src_images_dir: str,
    dst_images_dir: str,
    src_labels_dir: str,
    dst_labels_dir: str,
    split: str,
    scale: float,
) -> int:
    """
    Resizes all images in src_images_dir by `scale` and copies labels unchanged.

    Returns the number of images processed.
    """
    ensure_dirs(dst_images_dir, dst_labels_dir)

    image_files = [f for f in os.listdir(src_images_dir) if _is_image(f)]
    total = len(image_files)

    if total == 0:
        print(f"  [WARN] No images found in {src_images_dir}")
        return 0

    print(f"  Processing '{split}': {total} images …")

    sample_logged = False
    for i, filename in enumerate(image_files, start=1):
        # ---- Resize image -------------------------------------------------
        src_img_path = os.path.join(src_images_dir, filename)
        dst_img_path = os.path.join(dst_images_dir, filename)

        img = cv2.imread(src_img_path)
        if img is None:
            print(f"    [WARN] Could not read: {src_img_path} — skipping")
            continue

        orig_h, orig_w = img.shape[:2]
        new_w = max(1, int(round(orig_w * scale)))
        new_h = max(1, int(round(orig_h * scale)))

        # Log first image dimensions for verification
        if not sample_logged:
            print(f"    Sample: {orig_w}×{orig_h} → {new_w}×{new_h}")
            sample_logged = True

        resized = cv2.resize(img, (new_w, new_h), interpolation=cv2.INTER_AREA)
        cv2.imwrite(dst_img_path, resized)

        # ---- Copy label (unchanged — YOLO labels are normalized) ----------
        stem      = os.path.splitext(filename)[0]
        label_src = os.path.join(src_labels_dir, stem + ".txt")
        label_dst = os.path.join(dst_labels_dir, stem + ".txt")
        if os.path.isfile(label_src):
            shutil.copy2(label_src, label_dst)

        # ---- Progress print -----------------------------------------------
        if i % 100 == 0 or i == total:
            print(f"    {i}/{total} done", end="\r")

    print(f"    {total}/{total} done")
    return total


def write_lowres_yaml(
    eval_root: str,
    lowres_dataset_dir: str,
    nc: int,
    names: list,
) -> str:
    """
    Writes a YOLO-compatible data YAML for the low-res dataset.
    Returns the path to the written YAML file.
    """
    yaml_path = get_yaml_path(eval_root, VARIANT_LOWRES)
    ensure_dirs(os.path.dirname(yaml_path))

    base = lowres_dataset_dir.replace("\\", "/")

    content = (
        f"# Auto-generated by 02_prepare_lowres.py\n"
        f"# Low-resolution variant (scale={LOWRES_SCALE}) of the original YOLO dataset\n\n"
        f"path: {base}\n"
        f"train: images/train\n"
        f"val:   images/val\n"
        f"test:  images/test\n\n"
        f"nc: {nc}\n"
        f"names: {names}\n"
    )

    with open(yaml_path, "w", encoding="utf-8") as fh:
        fh.write(content)

    print(f"\n[OK] YAML written → {yaml_path}")
    return yaml_path


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Create a reduced-resolution (75%%) YOLO dataset from an existing one."
    )
    parser.add_argument(
        "--dataset_root",
        required=True,
        help="Path to the original YOLO dataset root (contains images/ and labels/).",
    )
    parser.add_argument(
        "--eval_root",
        required=True,
        help="Path to the robustness_eval/ folder (results/ will be created here).",
    )
    parser.add_argument(
        "--scale",
        type=float,
        default=LOWRES_SCALE,
        help=f"Scale factor for resizing (default: {LOWRES_SCALE} = 75%% of original).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing low-res dataset if it already exists.",
    )
    args = parser.parse_args()

    # ---- Validate inputs ---------------------------------------------------
    if not os.path.isdir(args.dataset_root):
        print(f"[ERROR] dataset_root does not exist: {args.dataset_root}")
        sys.exit(1)
    if not os.path.isdir(args.eval_root):
        print(f"[ERROR] eval_root does not exist: {args.eval_root}")
        sys.exit(1)
    if not (0.0 < args.scale < 1.0):
        print(f"[ERROR] --scale must be between 0 and 1 (exclusive). Got: {args.scale}")
        sys.exit(1)

    dataset_root = os.path.abspath(args.dataset_root)
    eval_root    = os.path.abspath(args.eval_root)
    scale        = args.scale

    # ---- Derive output directory -------------------------------------------
    lowres_dir = get_dataset_dir(dataset_root, VARIANT_LOWRES)
    print(f"\n{'='*60}")
    print(f"  Low-Resolution Dataset Preparation")
    print(f"{'='*60}")
    print(f"  Source      : {dataset_root}")
    print(f"  Destination : {lowres_dir}")
    print(f"  Scale       : {scale:.0%} of original dimensions")
    print(f"{'='*60}\n")

    if os.path.isdir(lowres_dir) and not args.force:
        print("[INFO] Low-res dataset directory already exists.")
        print("       Use --force to overwrite. Skipping resizing.")
    else:
        if os.path.isdir(lowres_dir) and args.force:
            print("[INFO] --force specified. Clearing existing low-res dataset …")
            shutil.rmtree(lowres_dir)

        grand_total = 0
        for split, img_dir, lbl_dir in _iter_splits(dataset_root):
            dst_img = os.path.join(lowres_dir, "images", split)
            dst_lbl = os.path.join(lowres_dir, "labels", split)
            count = resize_dataset(img_dir, dst_img, lbl_dir, dst_lbl, split, scale)
            grand_total += count

        print(f"\n[OK] Low-res conversion complete. Total images processed: {grand_total}")

    # ---- Write YAML --------------------------------------------------------
    write_lowres_yaml(
        eval_root=eval_root,
        lowres_dataset_dir=lowres_dir,
        nc=len(CLASS_NAMES),
        names=CLASS_NAMES,
    )

    print("\n[DONE] Step 2 complete. Next: run 03_train.py --variant grayscale\n")


if __name__ == "__main__":
    main()
